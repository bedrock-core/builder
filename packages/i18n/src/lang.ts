export const SECTION_BEGIN = '## <core:generated-i18n:begin> do not edit — generated by @bedrock-core';
export const SECTION_END = '## <core:generated-i18n:end>';

/** The branch holding the manifest display strings (name/description). */
export const PACK_BRANCH = 'pack';

/**
 * Parse a Minecraft .lang file into a key→value map. Lines starting with # are comments; blank lines are skipped. Format: key=value (value may contain '=').
 * @param content Language-file source text.
 * @returns Language keys mapped to parsed string values.
 */
export function parseLang(content: string): Record<string, string> {
  const map: Record<string, string> = {};

  for (const rawLine of content.split('\n')) {
    // Only the line ending goes: a value's trailing space is significant. A
    // piece of a composed paragraph line, "Back to ", ends in the space that
    // separates it from the link after it, and the client draws that space.
    const line = rawLine.endsWith('\r') ? rawLine.slice(0, -1) : rawLine;

    if (!line.trim() || line.trimStart().startsWith('#')) {
      continue;
    }

    const eqIdx = line.indexOf('=');

    if (eqIdx === -1) {
      continue;
    }

    const key = line.slice(0, eqIdx).trim();
    const value = line.slice(eqIdx + 1);

    if (key) {
      map[key] = value;
    }
  }

  return map;
}

/** Remove a previously generated section (returns content unchanged if none). */
export function stripGeneratedSection(content: string, section?: string): string {
  const suffix = section === undefined ? '' : `:${encodeURIComponent(section)}`;
  const begin = content.indexOf(`## <core:generated-i18n:begin${suffix}>`);

  if (begin === -1) {
    return content;
  }

  const endTag = `## <core:generated-i18n:end${suffix}>`;
  const endMarker = content.indexOf(endTag, begin);
  const end = endMarker === -1 ? content.length : endMarker + endTag.length;

  return (content.slice(0, begin) + content.slice(end)).replace(/\n{3,}$/, '\n\n');
}

/** Remove generated contributions from every producer when collecting authored passthrough text. */
export function stripAllGeneratedSections(content: string): string {
  let remaining = content;
  let match: RegExpExecArray | null;

  while ((match = /## <core:generated-i18n:begin(?::([^>]+))?>/.exec(remaining))) {
    remaining = stripGeneratedSection(remaining, match[1] === undefined ? undefined : decodeURIComponent(match[1]));
  }

  return remaining;
}

/** Remove replaced authored keys while preserving other producers' generated sections. */
export function stripLangEntries(content: string, keys: ReadonlySet<string>): string {
  let generated = false;

  return content.split(/(?<=\n)/).filter((line) => {
    if (line.startsWith('## <core:generated-i18n:begin')) {
      generated = true;
    }

    if (generated) {
      if (line.startsWith('## <core:generated-i18n:end')) {
        generated = false;
      }

      return true;
    }

    const separator = line.indexOf('=');

    return separator === -1 || !keys.has(line.slice(0, separator).trim());
  }).join('');
}

/**
 * Replace/append the generated section. Keys are emitted sorted for
 * deterministic output. `.lang` values must be single-line — enforced here
 * as a last line of defense (flattenResources rejects newlines first).
 */
export function upsertGeneratedSection(content: string, entries: Map<string, string>, section?: string): string {
  // Trailing blank lines go; a trailing space on the last value is part of that value.
  const base = stripGeneratedSection(content, section).replace(/(\r?\n[ \t]*)+$/, '');

  const suffix = section === undefined ? '' : `:${encodeURIComponent(section)}`;
  const lines = [section === undefined ? SECTION_BEGIN : `## <core:generated-i18n:begin${suffix}> generated by @bedrock-core`];

  for (const key of [...entries.keys()].sort()) {
    lines.push(`${key}=${String(entries.get(key)).replace(/\r?\n/g, ' ')}`);
  }

  lines.push(`## <core:generated-i18n:end${suffix}>`);

  return (base ? base + '\n\n' : '') + lines.join('\n') + '\n';
}

/**
 * The two literal keys Bedrock resolves a manifest header from. This is NOT a
 * general key lookup: the client reads `header.name` / `header.description`
 * only when they are exactly these strings, so `<namespace>.pack.name` in a
 * manifest shows up as the raw key in the pack list.
 */
export const MANIFEST_ALIASES: [leaf: string, alias: string][] = [
  ['name', 'pack.name'],
  ['description', 'pack.description'],
];

/**
 * Mirror the addon's `pack.name` / `pack.description` onto the literal
 * `pack.name` / `pack.description` keys, so a manifest can point at them.
 *
 * The namespaced originals stay — scripts resolve those through `key()`, and
 * they are what travels in the runtime bundle. These are aliases, emitted into
 * each pack's own generated section (both packs: RP and BP each have a
 * manifest of their own, and each resolves from its own texts file).
 *
 * Empty when neither display string is declared.
 */
export function manifestAliasEntries(entries: Map<string, string>, namespace: string): Map<string, string> {
  const out = new Map<string, string>();

  for (const [leaf, alias] of MANIFEST_ALIASES) {
    const value = entries.get(`${namespace}.${PACK_BRANCH}.${leaf}`);

    if (value !== undefined) {
      out.set(alias, value);
    }
  }

  return out;
}
