export interface BundleDtsOptions {
  defaultLocale: string;
  ownModule?: string;
  vanilla: boolean;
  libs: { namespace: string; typeRefs: string[] }[];
}

export function bundleDtsText({ defaultLocale, ownModule, vanilla, libs }: BundleDtsOptions): string {
  const ownSpecifier = ownModule?.replaceAll('\\', '\\\\').replaceAll('\'', '\\\'');
  const libAliases = libs.map(({ namespace, typeRefs }) => {
    const refs = typeRefs.map(ref => `typeof import('${ref}').default`).join(' & ');

    return `\ttype Lib_${namespace} = ${refs};`;
  });

  const branches = [
    ...libs.map(({ namespace }) => `readonly ${namespace}: Lib_${namespace};`),
    ...(vanilla ? [`readonly vanilla: import('@bedrock-core/generated/i18n-vanilla').VanillaResources;`] : []),
  ];

  // Authored overrides live under the branch names inside Own (e.g. a
  // `core.addons.title` rename) — Omit them so the graft replaces rather than
  // intersects, which would collapse overridden literals to `never`.
  const branchNames = [...libs.map(({ namespace }) => `'${namespace}'`), ...(vanilla ? ['\'vanilla\''] : [])];
  const resourcesType = branches.length > 0
    ? `Omit<Own, ${branchNames.join(' | ')}> & {\n\t\t\t${branches.join('\n\t\t\t')}\n\t\t}`
    : 'Own';

  return [
    '// Generated by @bedrock-core. Include this file in your TypeScript project.',
    'declare module \'@bedrock-core/generated/i18n\' {',
    ownSpecifier ? `\ttype Own = typeof import('${ownSpecifier}').default;` : '\ttype Own = Record<never, never>;',
    ...libAliases,
    '',
    '\tconst bundle: {',
    '\t\treadonly namespace: string;',
    `\t\treadonly defaultLocale: '${defaultLocale}';`,
    `\t\treadonly libs: readonly [${libs.map(({ namespace }) => `'${namespace}'`).join(', ')}];`,
    '\t\t/** locale → flat path → template ({{var}} form; vanilla entries only where referenced) */',
    '\t\treadonly locales: Record<string, Record<string, string>>;',
    '\t\t/** flat path → interpolation argument order (default locale appearance order) */',
    '\t\treadonly args: Record<string, readonly string[]>;',
    '\t\t/** locale → REAL key → value: .lang passthrough (guides, hand-written) for measurement */',
    '\t\treadonly extra: Record<string, Record<string, string>>;',
    '\t\t/** Type-only: the tree the t()/key()/raw() selectors navigate. Absent at runtime. */',
    `\t\treadonly resources?: ${resourcesType};`,
    '\t};',
    '\texport default bundle;',
    '}',
    '',
  ].join('\n').replaceAll('\t', '  ');
}
