// .lang file handling: parse, and idempotent upsert of the marker-delimited
// generated section (strip any previous section, then append the new one).

const SECTION_MARKER = '## <core:generated-guides:begin>';

export const SECTION_BEGIN = `${SECTION_MARKER} do not edit - generated by @bedrock-core`;
export const SECTION_END = '## <core:generated-guides:end>';

/**
 * Parse a Minecraft .lang file into a key→value map.
 * Lines starting with # are comments; blank lines are skipped.
 * Format: key=value (value may contain '=').
 */
export function parseLang(content: string): Record<string, string> {
  const map: Record<string, string> = {};

  for (const rawLine of content.split('\n')) {
    const line = rawLine.endsWith('\r') ? rawLine.slice(0, -1) : rawLine;

    if (!line.trim() || line.trimStart().startsWith('#')) {
      continue;
    }

    const eqIdx = line.indexOf('=');

    if (eqIdx === -1) {
      continue;
    }

    const key = line.slice(0, eqIdx).trim();
    const value = line.slice(eqIdx + 1); // preserve leading spaces in value

    if (key) {
      map[key] = value;
    }
  }

  return map;
}

/** Remove a previously generated section (returns content unchanged if none). */
export function stripGeneratedSection(content: string, section?: string): string {
  const suffix = section === undefined ? '' : `:${encodeURIComponent(section)}`;
  const begin = content.indexOf(`## <core:generated-guides:begin${suffix}>`);

  if (begin === -1) {
    return content;
  }

  const endTag = `## <core:generated-guides:end${suffix}>`;
  const endMarker = content.indexOf(endTag, begin);
  const end = endMarker === -1 ? content.length : endMarker + endTag.length;

  return (content.slice(0, begin) + content.slice(end)).replace(/\n{3,}$/, '\n\n');
}

/**
 * Replace/append the generated section. Keys are emitted sorted for
 * deterministic output. `.lang` values must be single-line — enforced here
 * as a last line of defense (the inline compiler never emits newlines).
 */
export function upsertGeneratedSection(content: string, entries: Map<string, string>, section?: string): string {
  const base = stripGeneratedSection(content, section).replace(/(\r?\n[ \t]*)+$/, '');
  const existing = parseLang(base);
  const suffix = section === undefined ? '' : `:${encodeURIComponent(section)}`;

  const lines = [section === undefined ? SECTION_BEGIN : `## <core:generated-guides:begin${suffix}> generated by @bedrock-core`];

  for (const key of [...entries.keys()].sort()) {
    const value = String(entries.get(key)).replace(/\r?\n/g, ' ');

    if (Object.hasOwn(existing, key) && existing[key] !== value) {
      throw new Error(`Conflicting guide translation for ${key}; use distinct namespaces for packs sharing a resource destination`);
    }

    lines.push(`${key}=${value}`);
  }

  lines.push(`## <core:generated-guides:end${suffix}>`);

  return (base ? base + '\n\n' : '') + lines.join('\n') + '\n';
}
